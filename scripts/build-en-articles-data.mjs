#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const contentRoots = [
  { directory: path.join(root, "en", "articles"), urlPrefix: "articles" },
  { directory: path.join(root, "en", "ai-trends"), urlPrefix: "ai-trends" }
];
const output = path.join(root, "en", "articles-data.js");
const writeMode = process.argv.includes("--write");

function decode(value) {
  return value
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}

function text(value) {
  return decode(value.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim());
}

function firstMatch(html, patterns) {
  for (const pattern of patterns) {
    const match = html.match(pattern);
    if (match) return text(match[1]);
  }
  return "";
}

const items = contentRoots.flatMap(({ directory, urlPrefix }) =>
  fs.readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
    const slug = entry.name;
    const file = path.join(directory, slug, "index.html");
    if (!fs.existsSync(file)) return null;
    const html = fs.readFileSync(file, "utf8");
    const title = firstMatch(html, [
      /<h1\b[^>]*>([\s\S]*?)<\/h1>/i,
      /<meta\s+property=["']og:title["']\s+content=["']([^"']+)["']/i,
      /<title>([\s\S]*?)<\/title>/i
    ]);
    const summary = firstMatch(html, [
      /<meta\s+name=["']description["']\s+content=["']([^"']+)["']/i,
      /<meta\s+property=["']og:description["']\s+content=["']([^"']+)["']/i
    ]);
    const date = firstMatch(html, [
      /"datePublished"\s*:\s*"([^"]+)"/i,
      /Published\s+(\d{4}-\d{2}-\d{2})/i
    ]).slice(0, 10);
    return { slug, title, summary, date, url: `${urlPrefix}/${slug}/` };
  })
  .filter(Boolean)
  .filter((item) => item.title))
  .sort((a, b) => (b.date || "").localeCompare(a.date || "") || a.title.localeCompare(b.title));

const generated = `/* Generated by scripts/build-en-articles-data.mjs. */\nwindow.EN_ARTICLES = ${JSON.stringify(items, null, 2)};\n`;

if (writeMode) {
  fs.writeFileSync(output, generated);
  console.log(`Wrote en/articles-data.js with ${items.length} English articles.`);
  process.exit(0);
}

if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== generated) {
  console.error("en/articles-data.js is stale. Run: node scripts/build-en-articles-data.mjs --write");
  process.exit(1);
}

console.log(`English article index PASS: ${items.length} pages.`);
